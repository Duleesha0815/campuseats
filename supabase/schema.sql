CREATE TABLE IF NOT EXISTS public.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL UNIQUE,
    CONSTRAINT ck_categories_name_not_empty CHECK (length(trim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS public.menu_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL,
    price numeric(10, 2) NOT NULL,
    category_id integer NOT NULL,
    available boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_menu_items_name_not_empty CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_menu_items_price_nonnegative CHECK (price >= 0),
    CONSTRAINT fk_menu_items_categories
        FOREIGN KEY (category_id)
        REFERENCES public.categories (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT uq_menu_items_category_name UNIQUE (category_id, name)
);

CREATE INDEX IF NOT EXISTS ix_menu_items_category_id
    ON public.menu_items (category_id);

